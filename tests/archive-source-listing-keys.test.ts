/**
 * Proves the `7z l -slt` key whitelist (archive-extraction-safety.ts) against real files of every archive
 * source the registry offers that 7-Zip reads: ISO, CAB, ARJ, RPM, DEB, CPIO, DMG, IMG, LZMA and Z, plus
 * LZH, WIM, CHM, SquashFS, VHD, MSI and NSIS. Each fixture under tests/fixtures/archive-sources was built by a
 * tool other than 7-Zip (see PROVENANCE there), so a key 7-Zip prints for a genuine file but the whitelist
 * does not know would turn a valid upload into a malformed-listing rejection. The expected bytes come from
 * the fixtures' known payload, never from the extraction under test.
 */


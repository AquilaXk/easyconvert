const AR_GLOBAL_HEADER = '!<arch>\n';
const AR_MEMBER_HEADER_BYTES = 60;
const AR_MEMBER_NAME_BYTES = 16;
const AR_MEMBER_SIZE_OFFSET = 48;
const AR_MEMBER_SIZE_BYTES = 10;


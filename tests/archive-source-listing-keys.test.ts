function readFixture(name: string): Buffer {
  return fs.readFileSync(path.join(FIXTURE_DIR, name));
}

/** Minimal ar(1) reader, independent of 7-Zip: the expected members of a .deb. */
function readArMember(archive: Buffer, memberName: string): Buffer {
  expect(archive.subarray(0, AR_GLOBAL_HEADER.length).toString('latin1')).toBe(AR_GLOBAL_HEADER);
  let offset = AR_GLOBAL_HEADER.length;
  while (offset + AR_MEMBER_HEADER_BYTES <= archive.length) {
    const name = archive.toString('latin1', offset, offset + AR_MEMBER_NAME_BYTES).trim().replace(/\/$/, '');
    const size = Number(archive.toString('latin1', offset + AR_MEMBER_SIZE_OFFSET, offset + AR_MEMBER_SIZE_OFFSET + AR_MEMBER_SIZE_BYTES).trim());
    const start = offset + AR_MEMBER_HEADER_BYTES;
    if (name === memberName) return archive.subarray(start, start + size);
    offset = start + size + (size % 2);
  }
  throw new Error(`ar member ${memberName} not found`);
}

interface Magic {
  /** Negative offsets count from the end of the file. */
  offset: number;
  bytes: Buffer;
}

function magic(offset: number, text: string | number[]): Magic {
  return { offset, bytes: typeof text === 'string' ? Buffer.from(text, 'latin1') : Buffer.from(text) };
}

interface SourceFixture {
  file: string;
  /** The registry source format (or the worker-only format) this file stands for. */
  format: string;
  /** Format-defining bytes proving the fixture is the claimed container, not renamed data. */
  magic: Magic[];
  /** Files the extraction must produce, byte for byte, keyed by forward-slash path. */
  expected: () => Record<string, Buffer>;
  /** When true the extraction must produce exactly the expected files and nothing else. */
  exact: boolean;
  /** Directory entries the listing carries (an empty volume still lists its root). */
  expectedEntryCount?: number;
  /** Source format id the worker route accepts for this container, when it extracts it. */
  workerFormat?: string;
}


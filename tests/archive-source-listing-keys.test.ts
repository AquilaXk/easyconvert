function assertMagic(buffer: Buffer, expected: Magic): void {
  const start = expected.offset < 0 ? buffer.length + expected.offset : expected.offset;
  expect(buffer.subarray(start, start + expected.bytes.length)).toEqual(expected.bytes);
}

function expectFilesEqual(actual: Map<string, Buffer>, fixture: SourceFixture): void {
  const expected = fixture.expected();
  for (const [relPath, bytes] of Object.entries(expected)) {
    const found = actual.get(relPath);
    if (found === undefined) {
      throw new Error(`${fixture.file}: ${relPath} was not extracted; got ${JSON.stringify([...actual.keys()].sort())}`);
    }
    expect(found.equals(bytes), `${fixture.file}: bytes of ${relPath}`).toBe(true);
  }
  if (fixture.exact) {
    expect([...actual.keys()].sort()).toEqual(Object.keys(expected).sort());
  }
}

describe('7z listing key whitelist on every native archive source', () => {
  const sevenZip = getOracleToolPath('7z');
  const originalP7zipPath = process.env.P7ZIP_PATH;
  let workDir: string;

  beforeAll(() => {
    if (sevenZip) process.env.P7ZIP_PATH = sevenZip;
    workDir = fs.mkdtempSync(path.join(os.tmpdir(), 'easyconvert-archive-sources-'));
  });

  afterAll(() => {
    if (originalP7zipPath === undefined) {
      delete process.env.P7ZIP_PATH;
    } else {
      process.env.P7ZIP_PATH = originalP7zipPath;
    }
    fs.rmSync(workDir, { recursive: true, force: true });
  });

  it('keeps one fixture per format the registry and worker route to 7-Zip', () => {
    const covered = new Set(FIXTURES.map((fixture) => fixture.format));
    for (const format of ['iso', 'cab', 'arj', 'rpm', 'deb', 'cpio', 'dmg', 'img', 'lzma', 'z', 'lzh', 'wim']) {
      expect(covered.has(format), `no fixture for ${format}`).toBe(true);
    }
  });

  for (const fixture of FIXTURES) {
    it(`${fixture.file} is a genuine ${fixture.format} container`, () => {
      const buffer = readFixture(fixture.file);
      for (const expected of fixture.magic) assertMagic(buffer, expected);
    });

    oracleTest(
      `library route extracts ${fixture.file} (${fixture.format}) byte for byte`,
      ['7z'],
      async () => {
        const caseDir = fs.mkdtempSync(path.join(workDir, 'lib-'));
        const archivePath = path.join(caseDir, fixture.file);
        fs.copyFileSync(path.join(FIXTURE_DIR, fixture.file), archivePath);
        const extractDir = path.join(caseDir, 'out');
        fs.mkdirSync(extractDir);

        const tree = await extractArchiveContained({
          p7zBin: sevenZip!,
          archivePath,
          extractDir,
          cwd: caseDir,
          timeoutMs: EXTRACT_TIMEOUT_MS,
          maxBuffer: ARCHIVE_SECURITY_LIMITS.MAX_UNCOMPRESSED_SIZE,
          limits: ARCHIVE_SECURITY_LIMITS,
          label: `${fixture.format.toUpperCase()} archive`,
        });

        const actual = new Map(tree.files.map((file) => [file.relPath, fs.readFileSync(file.absPath)]));
        expectFilesEqual(actual, fixture);
        if (fixture.expectedEntryCount !== undefined) {
          expect(tree.entryCount).toBe(fixture.expectedEntryCount);
        }
      },
      SLOW_TEST_TIMEOUT_MS
    );

    if (fixture.workerFormat) {
      const workerFormat = fixture.workerFormat;
      oracleTest(
        `worker route converts ${fixture.file} (${workerFormat}) to a zip holding the same bytes`,
        ['7z'],
        async () => {
          const result = await convertWithNative7z(readFixture(fixture.file), workerFormat, 'zip', {}, fixture.file);
          if (result === null) throw new Error('worker route declined the archive');
          const zip = await JSZip.loadAsync(result.buffer);
          const actual = new Map<string, Buffer>();
          for (const [name, entry] of Object.entries(zip.files)) {
            if (!entry.dir) actual.set(name, await entry.async('nodebuffer'));
          }
          expectFilesEqual(actual, fixture);
        },
        SLOW_TEST_TIMEOUT_MS
      );
    }
  }
});

describe('RAR5 listing keys', () => {
  // 7-Zip prints `Copy Link` (the RAR5 file-copy reference) for every RAR5 entry; written by hand from a 23.01 listing.
  const RAR5_BLOCK = [
    'Path = a.txt',
    'Folder = -',
    'Size = 11',
    'Packed Size = 16',
    'Encrypted = +',
    'Host OS = Unix',
    'Method = m0:17 AES:15:1',
    'Symbolic Link = ',
    'Hard Link = ',
    'Copy Link = ',
    '',
  ].join('\n');

  it('accepts the Copy Link field and still reads the entry', () => {
    const [entry] = parse7zTechnicalListing(RAR5_BLOCK);
    expect(entry.path).toBe('a.txt');
    expect(entry.sizeBytes).toBe(11);
    expect(entry.linkKind).toBeNull();
  });
});

describe('the password prompt is not part of a listing', () => {
  const LISTING = 'Path = a.txt\nSize = 2\n';

  it.each([
    ['p7zip and 7-Zip up to 23.01', 'Enter password (will not be echoed):'],
    ['7-Zip 26.01', 'Enter password:'],
  ])('strips the %s prompt so the listing parses', (_build, prompt) => {
    const [entry] = parse7zTechnicalListing(stripSevenZipPasswordPrompt(`\n${prompt}\n${LISTING}`));
    expect(entry.path).toBe('a.txt');
    expect(entry.sizeBytes).toBe(2);
  });

  it('leaves a line that only starts like the prompt for the parser to refuse', () => {
    expect(() => parse7zTechnicalListing(stripSevenZipPasswordPrompt(`Enter passwords here\n${LISTING}`))).toThrow(
      /unrecognized line/
    );
  });
});

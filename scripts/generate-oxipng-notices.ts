import fs from 'node:fs';
import path from 'node:path';
import { parse } from 'smol-toml';
import {
  APACHE_ID,
  APACHE_LICENSE_SHA256,
  APACHE_LICENSE_URL,
  APACHE_TEXT,
  block,
  CRATE_URL,
  type CrateLicence,
  downloadChecked,
  type LinkedCrate,
  licenceLine,
  linkedCrates,
  MAX_CRATE_BYTES,
  MAX_LICENSE_FILE_BYTES,
  MAX_RUST_SRC_BYTES,
  MUSL_VERSION,
  parseLockfile,
  readCrateLicence,
  RUST_COMMIT,
  RUST_SRC_SHA256,
  RUST_SRC_URL,
  RUST_VERSION,
  LIBUNWIND_COMMIT,
  sha256,
  STD_CRATES,
  textBlocks,
  TOOLCHAIN_TEXTS,
} from './generate-vtracer-notices';

/**
 * Writes scripts/oxipng-notices/THIRD-PARTY-NOTICES, the licence texts of the third-party code statically linked into the pinned oxipng
 * release program (scripts/install-oxipng.sh installs it beside the program's own licence). It does for oxipng what
 * scripts/generate-vtracer-notices.ts does for vtracer, with the same functions: the crates are the dependency graph of the `oxipng` package
 * in the Cargo.lock of the tagged commit (the lockfile that crates.io ships with the package is the same file), each crate's archive checked
 * against the checksum that lockfile records, and its LICENSE*, COPYING* and NOTICE* files read as data. The texts of the code the toolchain
 * links into every musl program (musl libc, LLVM libunwind, the Rust standard library and the crates it vendors) are the ones the vtracer notices
 * pin, at the same commits and digests: the release program is built by a nightly compiler (rustc 1.100.0-nightly, 5db7f4be8, 2026-09-01), whose
 * standard library vendors crates of these same projects under the same licences; the versions of those crates in the lines below are the
 * ones of Rust RUST_VERSION.
 *
 * The upstream files are fetched from the tagged commit, checked against the digests below and kept in scripts/oxipng-notices/upstream, so a
 * test can check the notices against the graph offline.
 *
 *   npx tsx scripts/generate-oxipng-notices.ts
 */

export const OXIPNG_VERSION = '10.2.1';
/** The commit that tag v10.2.1 names. */
export const OXIPNG_COMMIT = '36f3ef8aac65ecf1761739ea2f2e530281f1312b';
export const NOTICES_DIR = path.resolve(__dirname, 'oxipng-notices');
export const NOTICES_FILE = path.join(NOTICES_DIR, 'THIRD-PARTY-NOTICES');
export const UPSTREAM_DIR = path.join(NOTICES_DIR, 'upstream');
const PINNED_SUFFIX = '.pinned';
const LOCKFILE = 'Cargo.lock';
const MANIFEST = 'Cargo.toml';
const UPSTREAM_RAW_URL = `https://raw.githubusercontent.com/oxipng/oxipng/${OXIPNG_COMMIT}`;

/** SHA-256 of each upstream file at OXIPNG_COMMIT. */
export const UPSTREAM_DIGESTS: Readonly<Record<string, string>> = {
  [LOCKFILE]: '22f3f5ee510e8af2e78194091197d1a223c171381aab9bb3479f32379033f6bb',
  [MANIFEST]: 'f30ef8613f8c04f120ab8373dc94187f17b5b1be91e63487289c4cc5017f7f81',
};

export function readPinned(file: string): string {
  return fs.readFileSync(path.join(UPSTREAM_DIR, `${file}${PINNED_SUFFIX}`), 'utf8');
}

export function pinnedLinkedCrates(): LinkedCrate[] {
  const manifests = new Map([[MANIFEST, parse(readPinned(MANIFEST)) as Record<string, unknown>]]);
  return linkedCrates(parseLockfile(readPinned(LOCKFILE)), manifests, MANIFEST);
}

function render(licences: readonly CrateLicence[], std: readonly CrateLicence[], toolchain: ReadonlyArray<{ heading: string; text: string }>, apache: string): string {
  const offersApache = (licence: CrateLicence) => APACHE_ID.test(licence.license) && !licence.texts.some(({ text }) => APACHE_TEXT.test(text));
  const apacheFor = [...licences, ...std].filter(offersApache).map((licence) => `${licence.crate.name} ${licence.crate.version}`);
  return [
    `oxipng ${OXIPNG_VERSION}: third-party notices`,
    '',
    'The oxipng program (MIT, Joshua Holmer and contributors) is statically linked with Rust crates. The crates below are the dependency graph of',
    `its package in the Cargo.lock of commit ${OXIPNG_COMMIT}`,
    `(SHA-256 ${UPSTREAM_DIGESTS[LOCKFILE]}), without development dependencies. The lockfile does`,
    'not tell apart the crates used only to build the program, only on other platforms or only with a feature the release does not enable',
    '(`image`, `glob`), so they are named too. Each text below is copied unmodified from the crates.io archive of the crates named above it,',
    'checked against the Cargo.lock checksum. libdeflater links libdeflate (MIT, Eric Biggers), whose source libdeflate-sys ships and builds;',
    'its COPYING is among the texts. Generated by scripts/generate-oxipng-notices.ts.',
    '',
    'The release program is built for the musl targets by the project, with a nightly compiler (rustc 1.100.0-nightly, 5db7f4be8, 2026-09-01), so it',
    `also carries code no lockfile lists: musl libc ${MUSL_VERSION}, linked statically; LLVM libunwind; and the Rust standard library with the crates it`,
    `vendors, listed after the crates above at the versions of Rust ${RUST_VERSION}. These texts are the ones scripts/vtracer-notices pins: copied`,
    `unmodified from the rust-src component ${RUST_VERSION} (SHA-256 ${RUST_SRC_SHA256}), the release built from commit ${RUST_COMMIT};`,
    `the libunwind text is libunwind/LICENSE.TXT of rust-lang/llvm-project commit ${LIBUNWIND_COMMIT}. The notices of musl and of the Rust project`,
    'follow the crate texts, copied unmodified from the musl release tag and the Rust commit named in each heading.',
    '',
    'Where a crate is offered under several licences, the one elected is MIT, whose text and copyright line the crate ships and the',
    'notices include (Apache-2.0 for a crate that ships no MIT text with a copyright line). The lists mark the election of each such',
    'crate. compiler_builtins is MIT AND Apache-2.0 WITH LLVM-exception: the texts of both are included, with the one of the libm',
    'code of its math module.',
    '',
    `Crates (${licences.length}):`,
    ...licences.map(licenceLine),
    '',
    `Rust standard library crates (${std.length}):`,
    ...std.map(licenceLine),
    '',
    ...textBlocks([...licences, ...std]),
    ...toolchain.map(({ heading, text }) => block(heading, text)),
    block(`Apache License 2.0, the text offered without a copy by: ${apacheFor.join(', ')}`, apache),
  ].join('\n');
}

async function fetchUpstream(): Promise<void> {
  for (const [file, digest] of Object.entries(UPSTREAM_DIGESTS)) {
    const bytes = await downloadChecked(`${UPSTREAM_RAW_URL}/${file}`, digest, MAX_CRATE_BYTES);
    const target = path.join(UPSTREAM_DIR, `${file}${PINNED_SUFFIX}`);
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, bytes);
  }
}

async function main(): Promise<void> {
  await fetchUpstream();
  const licences: CrateLicence[] = [];
  for (const crate of pinnedLinkedCrates()) {
    const archive = await downloadChecked(`${CRATE_URL}/${crate.name}/${crate.name}-${crate.version}.crate`, crate.checksum, MAX_CRATE_BYTES);
    const prefix = `${crate.name}-${crate.version}/`;
    // libdeflate-sys builds the C source of libdeflate that it ships in a subdirectory, with that library's own licence text.
    const layout = crate.name === 'libdeflate-sys' ? { compression: 'z' as const, prefix, elsewhere: [{ member: `${prefix}libdeflate/COPYING`, label: 'libdeflate/COPYING' }] } : { compression: 'z' as const, prefix };
    licences.push(readCrateLicence(crate, archive, layout));
  }
  const rustSrc = await downloadChecked(RUST_SRC_URL, RUST_SRC_SHA256, MAX_RUST_SRC_BYTES);
  const std = STD_CRATES.map(({ id, layout }) => readCrateLicence(id, rustSrc, layout));
  const toolchain: Array<{ heading: string; text: string }> = [];
  for (const { heading, url, sha256: digest } of TOOLCHAIN_TEXTS) {
    toolchain.push({ heading, text: (await downloadChecked(url, digest, MAX_LICENSE_FILE_BYTES)).toString('utf8') });
  }
  const apache = (await downloadChecked(APACHE_LICENSE_URL, APACHE_LICENSE_SHA256, MAX_LICENSE_FILE_BYTES)).toString('utf8');
  fs.mkdirSync(NOTICES_DIR, { recursive: true });
  fs.writeFileSync(NOTICES_FILE, render(licences, std, toolchain, apache), 'utf8');
  console.log(`wrote ${path.relative(process.cwd(), NOTICES_FILE)}: ${licences.length} crates, SHA-256 ${sha256(fs.readFileSync(NOTICES_FILE))}`);
}

if (process.argv[1]?.endsWith('generate-oxipng-notices.ts')) {
  main().catch((error: unknown) => {
    console.error(error instanceof Error ? error.message : error);
    process.exitCode = 1;
  });
}

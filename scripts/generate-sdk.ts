import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { buildOpenApiDocument } from '../src/lib/api/openapi';
import { normalizeOpenApiForSdk } from './lib/sdk-openapi';

/**
 * Writes the generated parts of the SDKs from the OpenAPI document that `GET /api/v1/openapi.json` serves:
 *   sdk/typescript/src/generated   by openapi-typescript (npm devDependency, pinned in package.json)
 *   sdk/python/easyconvert/_generated   by openapi-python-client (pinned with hashes in sdk/python/generator-requirements.txt,
 *                                       installed into a virtual environment under node_modules/.cache on first use)
 * `--check` writes nothing: it generates into a temporary directory and exits 1 when a committed file differs.
 * The hand-written layers (sdk/typescript/src/client.ts, sdk/python/easyconvert/client.py) are never touched.
 */

const ROOT_DIR = path.resolve(__dirname, '..');
const TS_GENERATED_DIR = path.join(ROOT_DIR, 'sdk', 'typescript', 'src', 'generated');
const PY_GENERATED_DIR = path.join(ROOT_DIR, 'sdk', 'python', 'easyconvert', '_generated');
const PY_REQUIREMENTS = path.join(ROOT_DIR, 'sdk', 'python', 'generator-requirements.txt');
const PY_CONFIG = path.join(ROOT_DIR, 'sdk', 'python', 'generator-config.yml');
const PY_VENV_DIR = path.join(ROOT_DIR, 'node_modules', '.cache', 'easyconvert-sdk-python-generator');
const VENV_STAMP = 'requirements.sha256';
const CHECK_FLAG = '--check';
const IGNORED_DIRECTORY = '__pycache__';
const SOURCE_NOTE = 'from the OpenAPI document of GET /api/v1/openapi.json (scripts/generate-sdk.ts). Do not edit; run npm run sdk:generate.';

function sha256(content: Buffer | string): string {
  return createHash('sha256').update(content).digest('hex');
}

function npmGeneratorVersion(name: string): string {
  const manifest = JSON.parse(fs.readFileSync(path.join(ROOT_DIR, 'node_modules', name, 'package.json'), 'utf8')) as { version: string };
  return manifest.version;
}

function pythonGeneratorVersion(): string {
  const pin = /^openapi-python-client==(\S+)/m.exec(fs.readFileSync(PY_REQUIREMENTS, 'utf8'));
  if (!pin) throw new Error(`${PY_REQUIREMENTS} does not pin openapi-python-client`);
  return pin[1];
}

function listFiles(dir: string): string[] {
  if (!fs.existsSync(dir)) return [];
  return fs
    .readdirSync(dir, { withFileTypes: true, recursive: true })
    .filter((entry) => entry.isFile() && !entry.parentPath.split(path.sep).includes(IGNORED_DIRECTORY))
    .map((entry) => path.relative(dir, path.join(entry.parentPath, entry.name)))
    .sort();
}

function generateTypeScript(specFile: string, outDir: string): void {
  const outFile = path.join(outDir, 'schema.d.ts');
  fs.mkdirSync(outDir, { recursive: true });
  execFileSync(path.join(ROOT_DIR, 'node_modules', '.bin', 'openapi-typescript'), [specFile, '-o', outFile, '--default-non-nullable', 'false'], { stdio: 'pipe' });
  const header = `// Generated by openapi-typescript ${npmGeneratorVersion('openapi-typescript')} ${SOURCE_NOTE}\n`;
  fs.writeFileSync(outFile, header + fs.readFileSync(outFile, 'utf8'));
}

/** Installs the hashed requirements into the cached virtual environment unless it already holds exactly this file. */
function ensurePythonGeneratorEnvironment(): string {
  const wanted = sha256(fs.readFileSync(PY_REQUIREMENTS));
  const stampFile = path.join(PY_VENV_DIR, VENV_STAMP);
  const binDir = path.join(PY_VENV_DIR, 'bin');
  if (fs.existsSync(stampFile) && fs.readFileSync(stampFile, 'utf8') === wanted) return binDir;
  fs.rmSync(PY_VENV_DIR, { recursive: true, force: true });
  execFileSync('python3', ['-m', 'venv', PY_VENV_DIR], { stdio: 'inherit' });
  execFileSync(
    path.join(binDir, 'python'),
    ['-m', 'pip', 'install', '--quiet', '--require-hashes', '--no-deps', '--disable-pip-version-check', '-r', PY_REQUIREMENTS],
    { stdio: 'inherit' },
  );
  fs.writeFileSync(stampFile, wanted);
  return binDir;
}

function generatePython(specFile: string, outDir: string): void {
  const binDir = ensurePythonGeneratorEnvironment();
  const version = pythonGeneratorVersion();
  execFileSync(
    path.join(binDir, 'openapi-python-client'),
    ['generate', '--path', specFile, '--meta', 'none', '--config', PY_CONFIG, '--output-path', outDir],
    // ruff, which the generator runs on its output, is found through PATH; PYTHONHASHSEED keeps the output order fixed and RUFF_NO_CACHE keeps a .ruff_cache out of it.
    { stdio: 'pipe', env: { ...process.env, PATH: `${binDir}${path.delimiter}${process.env.PATH ?? ''}`, PYTHONHASHSEED: '0', RUFF_NO_CACHE: 'true' } },
  );
  const header = `# Generated by openapi-python-client ${version} ${SOURCE_NOTE}\n`;
  for (const file of listFiles(outDir)) {
    const target = path.join(outDir, file);
    fs.writeFileSync(target, header + fs.readFileSync(target, 'utf8'));
  }
}

/** Names every file that is missing, extra or different between the committed directory and a fresh one. */
function differences(committedDir: string, freshDir: string): string[] {
  const committed = new Set(listFiles(committedDir));
  const fresh = new Set(listFiles(freshDir));
  const problems: string[] = [];
  for (const file of [...new Set([...committed, ...fresh])].sort()) {
    const shown = path.relative(ROOT_DIR, path.join(committedDir, file));
    if (!fresh.has(file)) problems.push(`${shown} is no longer generated`);
    else if (!committed.has(file)) problems.push(`${shown} is not committed`);
    else if (!fs.readFileSync(path.join(committedDir, file)).equals(fs.readFileSync(path.join(freshDir, file)))) problems.push(`${shown} differs`);
  }
  return problems;
}

function replaceDirectory(target: string, source: string): void {
  fs.rmSync(target, { recursive: true, force: true });
  fs.cpSync(source, target, { recursive: true });
  console.log(`wrote ${path.relative(ROOT_DIR, target)}`);
}

function main(): void {
  const work = fs.mkdtempSync(path.join(os.tmpdir(), 'easyconvert-sdk-'));
  try {
    const specFile = path.join(work, 'openapi.json');
    fs.writeFileSync(specFile, JSON.stringify(normalizeOpenApiForSdk(buildOpenApiDocument()), null, 2));
    const targets = [
      { committed: TS_GENERATED_DIR, fresh: path.join(work, 'typescript'), generate: generateTypeScript },
      { committed: PY_GENERATED_DIR, fresh: path.join(work, 'python'), generate: generatePython },
    ];
    for (const target of targets) target.generate(specFile, target.fresh);
    if (!process.argv.includes(CHECK_FLAG)) {
      for (const target of targets) replaceDirectory(target.committed, target.fresh);
      return;
    }
    const problems = targets.flatMap((target) => differences(target.committed, target.fresh));
    for (const problem of problems) console.error(problem);
    if (problems.length > 0) {
      console.error('The generated SDK is out of date; run npm run sdk:generate');
      process.exitCode = 1;
    }
  } finally {
    fs.rmSync(work, { recursive: true, force: true });
  }
}

main();

// Refreshes the vendored blocklist of disposable email domains (CC0 1.0) and rebuilds the module the server loads.
//
//   node scripts/refresh-disposable-email-domains.mjs [--ref <branch|tag|sha>]   fetch the list, pin its commit, rebuild
//   node scripts/refresh-disposable-email-domains.mjs --build                    rebuild the module from the vendored list
//   node scripts/refresh-disposable-email-domains.mjs --check                    exit 1 when the module is not the vendored list
//
// Only this script reads the network, and only when run by hand: the running server never fetches the list. After a fetch,
// review `git diff --stat third_party/disposable-email-domains` and commit the three files it changes with the module.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO = 'disposable-email-domains/disposable-email-domains';
const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const VENDOR_DIR = join(ROOT, 'third_party', 'disposable-email-domains');
const LIST_PATH = join(VENDOR_DIR, 'disposable_email_blocklist.conf');
const LICENSE_PATH = join(VENDOR_DIR, 'LICENSE.txt');
const SOURCE_PATH = join(VENDOR_DIR, 'SOURCE.md');
const MODULE_PATH = join(ROOT, 'src', 'lib', 'auth', 'disposable-email-domains.generated.ts');
const DOMAIN = /^[a-z0-9](?:[a-z0-9-]*[a-z0-9])?(?:\.[a-z0-9](?:[a-z0-9-]*[a-z0-9])?)+$/;

async function getText(url) {
  const response = await fetch(url, { headers: { 'user-agent': 'easyconvert-refresh-disposable-email-domains' } });
  if (!response.ok) throw new Error(`${url}: HTTP ${response.status}`);
  return response.text();
}

/** The domains of a list in the upstream format (one lower-case domain per line), or an error naming the bad line. */
function parseList(text) {
  const domains = text.split('\n').filter((line) => line !== '');
  const bad = domains.find((domain) => !DOMAIN.test(domain));
  if (bad !== undefined) throw new Error(`the list has a line that is not a lower-case domain: ${JSON.stringify(bad)}`);
  if (domains.length < 1000) throw new Error(`the list has only ${domains.length} domains; refusing to replace the vendored copy`);
  return domains;
}

/** The domains packed into lines of about 160 characters, so that 10,000 of them are a file of a few hundred lines. */
function packLines(domains) {
  const lines = [];
  let line = '';
  for (const domain of domains) {
    if (line !== '' && line.length + 1 + domain.length > 160) {
      lines.push(line);
      line = '';
    }
    line = line === '' ? domain : `${line} ${domain}`;
  }
  if (line !== '') lines.push(line);
  return lines;
}

function renderModule(domains, commit) {
  return [
    '// Generated by scripts/refresh-disposable-email-domains.mjs; do not edit by hand.',
    `// Source: https://github.com/${REPO} (disposable_email_blocklist.conf at commit ${commit}), CC0 1.0 Universal.`,
    '// See third_party/disposable-email-domains/SOURCE.md.',
    'const PACKED_DOMAINS = [',
    ...packLines(domains).map((line) => `  '${line}',`),
    '];',
    '',
    "export const DISPOSABLE_EMAIL_DOMAINS: readonly string[] = PACKED_DOMAINS.join(' ').split(' ');",
    '',
  ].join('\n');
}

function pinnedCommit() {
  const match = /^- Commit: `([0-9a-f]{40})`$/m.exec(readFileSync(SOURCE_PATH, 'utf8'));
  if (!match) throw new Error('SOURCE.md names no commit');
  return match[1];
}

function renderSource(commit, domains) {
  return [
    '# Disposable email domains',
    '',
    `- Repository: https://github.com/${REPO}`,
    '- Path: `disposable_email_blocklist.conf`, `LICENSE.txt`',
    `- Commit: \`${commit}\``,
    `- Fetched: ${new Date().toISOString().slice(0, 10)}`,
    `- Domains: ${domains.length}`,
    '- Licence: CC0 1.0 Universal (public domain dedication, `LICENSE.txt`)',
    '',
    'The list is vendored whole so that the server never reads the network for it. `src/lib/auth/disposable-email-domains.generated.ts` is',
    'built from it by `scripts/refresh-disposable-email-domains.mjs`; `tests/disposable-email.test.ts` fails when the two differ.',
    '',
    'Refresh: `node scripts/refresh-disposable-email-domains.mjs` (the default branch) or `--ref <sha>`, then commit the changed files.',
    '',
  ].join('\n');
}

const args = process.argv.slice(2);
if (args.includes('--check')) {
  const expected = renderModule(parseList(readFileSync(LIST_PATH, 'utf8')), pinnedCommit());
  if (readFileSync(MODULE_PATH, 'utf8') !== expected) {
    console.error('src/lib/auth/disposable-email-domains.generated.ts is not the vendored list: run scripts/refresh-disposable-email-domains.mjs --build');
    process.exit(1);
  }
} else if (args.includes('--build')) {
  writeFileSync(MODULE_PATH, renderModule(parseList(readFileSync(LIST_PATH, 'utf8')), pinnedCommit()));
} else {
  const refIndex = args.indexOf('--ref');
  const ref = refIndex >= 0 ? args[refIndex + 1] : undefined;
  if (refIndex >= 0 && !ref) throw new Error('--ref needs a branch, tag or commit');
  const commitInfo = await getText(`https://api.github.com/repos/${REPO}/commits/${ref ?? 'main'}`);
  const commit = JSON.parse(commitInfo).sha;
  if (!/^[0-9a-f]{40}$/.test(commit)) throw new Error('GitHub named no commit for the ref');
  const raw = (path) => getText(`https://raw.githubusercontent.com/${REPO}/${commit}/${path}`);
  const list = await raw('disposable_email_blocklist.conf');
  const domains = parseList(list);
  writeFileSync(LIST_PATH, list);
  writeFileSync(LICENSE_PATH, await raw('LICENSE.txt'));
  writeFileSync(SOURCE_PATH, renderSource(commit, domains));
  writeFileSync(MODULE_PATH, renderModule(domains, commit));
  console.log(`vendored ${domains.length} domains from ${REPO}@${commit}`);
}

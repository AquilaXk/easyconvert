#!/usr/bin/env bash
# Installs the pinned oxipng release program, the lossless optimiser of PNG files (the PNG to PNG conversions, entry 232 of
# docs/policy-decisions.md). oxipng (Joshua Holmer and contributors) is MIT; the program is the project's own statically linked musl
# build from its release page, used unmodified and only as a separate
# program: it is never linked into the application. The archive and the licence text are each verified against a fixed SHA-256
# before anything in them runs or is copied, and the licence text comes from the tagged commit, not a branch.
#
# The program is statically linked with the Rust crates of its dependency graph, the Rust standard library and musl libc; their licence
# texts are the THIRD-PARTY-NOTICES file of scripts/oxipng-notices, generated by scripts/generate-oxipng-notices.ts and checked here by
# digest before anything is downloaded.
#
# Bump OXIPNG_VERSION, OXIPNG_COMMIT (the commit the tag names), the release digests, the licence digest and the notices together:
# regenerate the notices for the new commit, and run tests/png-optimise.test.ts with the new program before moving the pin.
#
# Usage: install-oxipng.sh [install-dir]   (default /opt/oxipng; linux x86_64 or aarch64; needs curl, tar and sha256sum)
# Installs <install-dir>/bin/oxipng, the licence text at <install-dir>/share/doc/oxipng/copyright with THIRD-PARTY-NOTICES and a
# SOURCE note beside it, and links the program into /usr/local/bin when it is run as root and the directory is not /usr/local.
set -euo pipefail

OXIPNG_VERSION="10.2.1"
OXIPNG_COMMIT="36f3ef8aac65ecf1761739ea2f2e530281f1312b"
OXIPNG_SHA256_AARCH64="ff21aa2a005b324c8dfbdf13cd2f469fb6728b27dacded82635824ecd12e3b35"
OXIPNG_SHA256_X86_64="1813750ef592c5350ca79c88f98b2c0876d05c826dc7156245256d4255c1ad17"
OXIPNG_LICENSE_SHA256="1bc9688d785fa50345f803824ddde000bdabedda9d1803dc41a1fedd81f784fc"
OXIPNG_NOTICES_SHA256="9b6db84f383ddd539c16d965f66c92979308d863294d79807a2fbb5b7ebf3dcd"
# The release archive is about 0.5 MB. curl refuses a download whose announced size is larger, and fetch stops reading at the bound
# plus one byte whatever the server announces, so that nothing larger than the bound is written before its digest is checked.
MAX_DOWNLOAD_BYTES=$((16 * 1024 * 1024))
INSTALL_DIR="${1:-/opt/oxipng}"
notices="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/oxipng-notices/THIRD-PARTY-NOTICES"

# The pinned programs are Linux builds; elsewhere (macOS reports arm64 too) there is nothing to install.
if [ "$(uname -s)" != "Linux" ]; then
  echo "install-oxipng.sh: the pinned oxipng builds are for Linux, not $(uname -s)" >&2
  exit 1
fi
case "$(uname -m)" in
  aarch64 | arm64)
    target="aarch64-unknown-linux-musl"
    digest="$OXIPNG_SHA256_AARCH64"
    ;;
  x86_64 | amd64)
    target="x86_64-unknown-linux-musl"
    digest="$OXIPNG_SHA256_X86_64"
    ;;
  *)
    echo "install-oxipng.sh: no pinned oxipng build for $(uname -m)" >&2
    exit 1
    ;;
esac
OXIPNG_URL="https://github.com/oxipng/oxipng/releases/download/v${OXIPNG_VERSION}/oxipng-${OXIPNG_VERSION}-${target}.tar.gz"
OXIPNG_LICENSE_URL="https://raw.githubusercontent.com/oxipng/oxipng/${OXIPNG_COMMIT}/LICENSE"

echo "${OXIPNG_NOTICES_SHA256}  $notices" | sha256sum --check --strict -
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

fetch() {
  local status=0
  curl --proto '=https' --proto-redir '=https' --tlsv1.2 --max-filesize "$MAX_DOWNLOAD_BYTES" --fail --silent --show-error --location --retry 6 --retry-delay 10 -o - "$2" \
    | head -c "$((MAX_DOWNLOAD_BYTES + 1))" > "$1" || status=$?
  if [ "$(wc -c < "$1")" -gt "$MAX_DOWNLOAD_BYTES" ]; then
    echo "install-oxipng.sh: $2 is larger than $MAX_DOWNLOAD_BYTES bytes" >&2
    exit 1
  fi
  if [ "$status" -ne 0 ]; then
    echo "install-oxipng.sh: the download of $2 failed (status $status)" >&2
    exit 1
  fi
}

# With OXIPNG_DOWNLOADS set (CI), a download kept there from an earlier run is used when its digest still matches, and a fresh
# one is kept there for the next run. The digest is checked on every use either way.
cached_fetch() {
  local name="$1" url="$2" sum="$3"
  if [ -n "${OXIPNG_DOWNLOADS:-}" ] && echo "${sum}  ${OXIPNG_DOWNLOADS}/${name}" | sha256sum --check --strict --status - 2>/dev/null; then
    cp "${OXIPNG_DOWNLOADS}/${name}" "$work/${name}"
  else
    fetch "$work/${name}" "$url"
  fi
  echo "${sum}  $work/${name}" | sha256sum --check --strict -
  if [ -n "${OXIPNG_DOWNLOADS:-}" ]; then cp "$work/${name}" "${OXIPNG_DOWNLOADS}/${name}"; fi
}

cached_fetch "oxipng-${target}.tar.gz" "$OXIPNG_URL" "$digest"
mv "$work/oxipng-${target}.tar.gz" "$work/oxipng.tar.gz"
cached_fetch "LICENSE-${OXIPNG_COMMIT}" "$OXIPNG_LICENSE_URL" "$OXIPNG_LICENSE_SHA256"
mv "$work/LICENSE-${OXIPNG_COMMIT}" "$work/LICENSE"
tar -xzf "$work/oxipng.tar.gz" -C "$work" --strip-components=1 "oxipng-${OXIPNG_VERSION}-${target}/oxipng"

install -d "$INSTALL_DIR/bin" "$INSTALL_DIR/share/doc/oxipng"
install -m 0755 "$work/oxipng" "$INSTALL_DIR/bin/oxipng"
# The Debian-style name, so the image collects it into /licenses with the system notices.
install -m 0644 "$work/LICENSE" "$INSTALL_DIR/share/doc/oxipng/copyright"
install -m 0644 "$notices" "$INSTALL_DIR/share/doc/oxipng/THIRD-PARTY-NOTICES"
printf 'oxipng %s (Joshua Holmer and contributors), unmodified release program %s\nSHA-256 %s\nSource: https://github.com/oxipng/oxipng/tree/%s\n' \
  "$OXIPNG_VERSION" "$OXIPNG_URL" "$digest" "$OXIPNG_COMMIT" > "$INSTALL_DIR/share/doc/oxipng/SOURCE"

if [ "$(id -u)" -eq 0 ] && [ "$INSTALL_DIR" != "/usr/local" ]; then
  ln -sf "$INSTALL_DIR/bin/oxipng" /usr/local/bin/oxipng
fi
"$INSTALL_DIR/bin/oxipng" --version
